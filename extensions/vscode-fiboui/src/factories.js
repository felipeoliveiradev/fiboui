module.exports.FACTORY_SET = new Set(module.exports.FACTORIES);

const FACTORY_CALL_RE = new RegExp(
  `\\b(?:${module.exports.FACTORIES.join('|')})\\s*\\(`
);

/**
 * True when a nearby source slice is a FiboUI fluent chain, not `function App()`
 * or `new Error(`.
 * @param {string} slice
 */
function sliceLooksLikeBuilder(slice) {
  if (typeof slice !== 'string' || !slice) return false;
  if (/\.(children|items)\s*\(/.test(slice)) return true;
  return FACTORY_CALL_RE.test(slice);
}

module.exports.FACTORY_CALL_RE = FACTORY_CALL_RE;
module.exports.sliceLooksLikeBuilder = sliceLooksLikeBuilder;
